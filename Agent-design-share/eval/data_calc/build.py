def main():
    passages, cases = [], []
    for fid, dom, concept, title, text, q, *answers in F:
        passages.append({"id": fid + "-p", "domain": dom, "topic": concept, "title": title, "text": text,
                         "source": "教材常识", "quality": "good"})
        for kind, ans in zip(("strong", "arith", "method"), answers):
            checks = calc.check(ans)
            assert checks, (fid, kind, "no calculation found")
            ok = all(c["ok"] for c in checks)
            assert ok == (kind != "arith"), (fid, kind, checks)  # only the arith answer contains a wrong result
            cases.append({"id": f"{fid}-{kind[0]}", "family": fid, "domain": dom, "split": "test", "question": q,
                          "concept": concept, "answer_type": "strong" if kind == "strong" else "flawed",
                          "flaw": "" if kind == "strong" else kind, "answer": ans})
    for name, rows in (("passages", passages), ("cases", cases)):
        (ROOT / f"{name}.jsonl").write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n")
    print(f"{len(passages)} passages, {len(cases)} cases; every calculation checked")


if __name__ == "__main__":
    main()
